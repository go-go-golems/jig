const section = j.sketch('section', { on: j.plane.XY })
  .rect('square', 10, 10, { center: true })
const column = j.part('Column')
  .extrude(section.profiles(), mm(100), { id: 'column' })

return j.fea('Column under pressure', { part: column })
  .material(j.material('PLA'))
  .params({ p: MPa(0.01) })
  .roller(j.feat('column').startFace(), { label: 'base' })
  .roller(j.sel.faces('<X'), { label: 'X guide' })
  .roller(j.sel.faces('<Y'), { label: 'Y guide' })
  .pressure(j.feat('column').endFace(), 'p', { label: 'top pressure' })
  .gravity()
  .mesh({ size: mm(5), refine: false })
