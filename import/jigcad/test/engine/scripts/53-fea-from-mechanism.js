// A stress study that takes its loads from a mechanism: the needle-bar slider-crank of 43, in steel, at 3000
// stitches a minute, with 4 N on the needle bar while it is down. The link's two bores seat its joints; the one
// toward the crank is held, the wrist carries what the mechanism says, and the link's own inertia loads it.
const r = 15.5, L = 60
const bar = (name, len, w, t) => j.part(name).material(j.material('steel'))
  .extrude(j.sketch('s', { on: j.plane.XY }).rect('r', len + w, w, { center: true }).profiles(), mm(t), { id: 'body' })
const crank = bar('crank', r, 14, 6).port('pivot', j.frame({ origin: j.pt(-r / 2, 0, 0), x: j.dir('+X'), z: j.dir('+Z') }))
  .port('pin', j.frame({ origin: j.pt(r / 2, 0, 6), x: j.dir('-X'), z: j.dir('+Z') }))
const rod = j.part('rod').material(j.material('steel'))
  .extrude(j.sketch('s', { on: j.plane.XY }).rect('r', L + 12, 12, { center: true })
    .circle('big', 3, { at: [-L / 2, 0] }).circle('small', 2.5, { at: [L / 2, 0] }).profiles(), mm(5), { id: 'body' })
  .port('big', j.frame({ origin: j.pt(-L / 2, 0, 0), x: j.dir('+X'), z: j.dir('+Z') }))
  .port('small', j.frame({ origin: j.pt(L / 2, 0, 0), x: j.dir('-X'), z: j.dir('+Z') }))
const slider = bar('slider', 6, 12, 6).port('wrist', j.frame({ origin: j.pt(0, 0, 6), x: j.dir('+Y'), z: j.dir('+Z') }))
  .port('guide', j.frame({ origin: j.pt(0, 0, 3), x: j.dir('+X'), z: j.dir('-Y') }))
const frame = j.part('frame')
  .extrude(j.sketch('p', { on: j.plane.offset(j.plane.XY, -4) }).rect('r', 50, 130, { center: true }).profiles(), mm(4), { id: 'plate' })
  .port('main', j.frame({ origin: j.pt(0, 0, 0), x: j.dir('-Y'), z: j.dir('+Z') }))
  .port('guide', j.frame({ origin: j.pt(0, 0, 3), x: j.dir('+X'), z: j.dir('-Y') }))
const head = j.assembly('needle-bar drive')
  .add('frame', frame, { ground: true }).add('crank', crank).add('rod', rod).add('slider', slider)
  .joint('main', j.joint.revolute(), 'frame:main', 'crank:pivot')
  .joint('pin', j.joint.revolute(), 'crank:pin', 'rod:big')
  .joint('wrist', j.joint.revolute(), 'rod:small', 'slider:wrist')
  .joint('guide', j.joint.prismatic(), 'frame:guide', 'slider:guide')
  .drive('main', deg(30)).hint('pin', deg(180))
  .measure('clamp', m => m.point('slider:wrist')[1])
  .study('cycle', { drive: 'main', from: deg(0), to: deg(360), steps: 360 })
  .speed('main', turn(3000).div(minute(1)))
  .gravity('-Y')
  .wrench('slider:wrist', row => row.clamp < -70 ? [0, N(4), 0] : null, { label: 'needle in the cloth' })
  .reactions('cycle')
return j.fea('link', { margin: 2 })
  .from(head, { component: 'rod', study: 'cycle' })
  .mesh({ size: mm(3) })
