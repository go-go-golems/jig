// A four-bar from parts: the take-up of a lockstitch head. The hints choose the open closure; the eye's path is
// compared with the closed form in the test.
const r = 15.5, coupler = 42.625, rocker = 36.8125, eye = 67.8125, D = [-14.53125, 29.0625]
const bar = (name, len, w, t) => j.part(name)
  .extrude(j.sketch('s', { on: j.plane.XY }).rect('r', len + w, w, { center: true }).profiles(), mm(t), { id: 'body' })
const crank = bar('crank', r, 14, 6).port('pivot', j.frame({ origin: j.pt(-r / 2, 0, 0), x: j.dir('+X'), z: j.dir('+Z') }))
  .port('pin', j.frame({ origin: j.pt(r / 2, 0, 6), x: j.dir('-X'), z: j.dir('+Z') }))
const lever = bar('lever', eye, 9, 3.5).port('a', j.frame({ origin: j.pt(-eye / 2, 0, 0), x: j.dir('+X'), z: j.dir('+Z') }))
  .port('b', j.frame({ origin: j.pt(coupler - eye / 2, 0, 3.5), x: j.dir('+X'), z: j.dir('+Z') }))
  .port('eye', j.frame({ origin: j.pt(eye / 2, 0, 0), x: j.dir('-X'), z: j.dir('+Z') }))
const link = bar('link', rocker, 8, 3.5).port('pivot', j.frame({ origin: j.pt(-rocker / 2, 0, 0), x: j.dir('+X'), z: j.dir('+Z') }))
  .port('end', j.frame({ origin: j.pt(rocker / 2, 0, 0), x: j.dir('-X'), z: j.dir('+Z') }))
const frame = j.part('frame')
  .extrude(j.sketch('p', { on: j.plane.offset(j.plane.XY, -4) }).rect('r', 90, 75, { center: true }).profiles(), mm(4), { id: 'plate' })
  .port('main', j.frame({ origin: j.pt(0, 0, 0), x: j.dir('-Y'), z: j.dir('+Z') }))
  .port('D', j.frame({ origin: j.pt(D[0], D[1], 9.5), x: j.dir('+X'), z: j.dir('+Z') }))
return j.assembly('take-up')
  .add('frame', frame, { ground: true }).add('crank', crank).add('lever', lever).add('link', link)
  .joint('main', j.joint.revolute(), 'frame:main', 'crank:pivot')
  .joint('pin', j.joint.revolute(), 'crank:pin', 'lever:a')
  .joint('rock', j.joint.revolute(), 'frame:D', 'link:pivot')
  .joint('elbow', j.joint.revolute(), 'link:end', 'lever:b')
  .drive('main', deg(0))
  .hint('pin', deg(66)).hint('rock', deg(-132))
  .measure('eye', m => m.point('lever:eye'))
  .measure('eyeY', m => m.point('lever:eye')[1])
  .measure('mu', m => { const a = m.angle('lever:b', 'link:end'); return Math.min(a, 180 - a) })
  .study('cycle', { drive: 'main', steps: 720 })
