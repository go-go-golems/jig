// Subassemblies: a flexible drive (its wheel turns inside the parent, geared 2:1 to the parent's arm) and a rigid
// bracket (solved on its own with its tilt at 20°, then swung as one body on the parent's pivot).
const block = (name, l, w, t) => j.part(name).extrude(j.sketch('s', { on: j.plane.XY }).rect('r', l, w, { center: true }).profiles(), mm(t), { id: 'body' })
const axle = j.frame({ origin: j.pt(0, 0, 0), x: j.dir('+X'), z: j.dir('+Z') })
const base = block('base', 30, 30, 2).port('axle', j.frame({ origin: j.pt(0, 0, 2), x: j.dir('+X'), z: j.dir('+Z') }))
const wheel = block('wheel', 20, 4, 2).port('axle', axle).port('mark', j.frame({ origin: j.pt(10, 0, 2), x: j.dir('+X'), z: j.dir('+Z') }))
const drive = j.assembly('wheel drive')
  .add('base', base, { ground: true }).add('wheel', wheel)
  .joint('spin', j.joint.revolute(), 'base:axle', 'wheel:axle')
  .measure('markY', m => m.point('wheel:mark')[1])
  .report('markNow', s => s.measures.markY, { unit: 'mm' })
const p1 = block('p1', 20, 10, 3).port('pivot', axle).port('hinge', j.frame({ origin: j.pt(10, 0, 3), x: j.dir('+X'), z: j.dir('+Y') }))
const p2 = block('p2', 20, 10, 3).port('hinge', j.frame({ origin: j.pt(-10, 0, 0), x: j.dir('+X'), z: j.dir('+Y') }))
const bracket = j.assembly('bracket')
  .add('p1', p1, { ground: true }).add('p2', p2)
  .joint('tilt', j.joint.revolute(), 'p1:hinge', 'p2:hinge')
  .drive('tilt', deg(20))
  .measure('tipZ', m => m.point('p2', [10, 0, 0])[2])
  .study('fold', { drive: 'tilt', from: deg(0), to: deg(90), steps: 9 })
  .report('drop', s => s.studies.fold.range('tipZ'), { unit: 'mm' })
const frame = block('frame', 140, 60, 2).port('main', j.frame({ origin: j.pt(-40, 0, 2), x: j.dir('+X'), z: j.dir('+Z') }))
  .port('pivot', j.frame({ origin: j.pt(0, 20, 2), x: j.dir('+X'), z: j.dir('+Z') }))
const arm = block('arm', 20, 6, 2).port('axle', axle)
return j.assembly('machine')
  .add('frame', frame, { ground: true }).add('arm', arm)
  .add('drive', drive, { at: j.tx.move(40, 0, 2), flexible: true })
  .add('bracket', bracket)
  .joint('main', j.joint.revolute(), 'frame:main', 'arm:axle')
  .joint('swing', j.joint.revolute(), 'frame:pivot', 'bracket/p1:pivot')
  .drive('main', deg(30)).drive('swing', deg(0))
  .couple('gear', 'main', 'drive/spin', { ratio: 2 })
  .measure('mark', m => m.point('drive/wheel:mark'))
  .measure('p2', m => m.point('bracket/p2', [0, 0, 0]))
